"""The companion app prototype's fixtures (Dan's ruling 61), drawn from the committed exports and nothing else.

    python tools/app_fixtures.py           write app/fixtures.js and copy the fixture pictures to app/fixtures/
    python tools/app_fixtures.py --check   regenerate both and compare with what is committed

Every model number in the fixtures is Decider's own answer as an export recorded it, with the export named on the
item: the photo holds and the unsure scenes from the final photo run (bench/image_eval_2026-10-22_final.json), the
transcript hold and the tasks' project answers from the server-variants run's CPU row
(bench/server_variants_2026-10-21.json, which keeps every project's probability). The content behind them is the
repository's fictional fixtures: the rendered pictures of bench/images/, the recording of bench/fixtures/rec_014, and
the canonical tasks of the fixtures' `expected` blocks. Nothing from Dan's live ledger, and no secret, is read.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from ratatoskr_demo.config import Settings  # noqa: E402
from ratatoskr_demo.devices.glasses_adapter import photo_id  # noqa: E402
from ratatoskr_demo.expected import canonical_tasks, load_expected  # noqa: E402
from ratatoskr_demo.route import load_route_questions  # noqa: E402
from ratatoskr_demo.transcript import extract_text  # noqa: E402

APP = REPO / "app"
OUT = APP / "fixtures.js"
PICTURES = APP / "fixtures"
FINAL = "bench/image_eval_2026-10-22_final.json"
VARIANTS = "bench/server_variants_2026-10-21.json"
PROJECTS = ("research", "school", "work", "writing", "community", "personal", "other")
# The holds and scenes the scenarios use (ruling 61; the brief's scenario A), from the final photo run
PHOTO_HOLDS = ("s2_prescription_label.png", "s6_counselling_card.png")
SCENES = ("o5_meeting_agenda.png", "o8_todo_list.png")
TRANSCRIPT_HOLD = "rec_014"
# The tasks: those Decider was unsure of (scenarios B and C) and some it was sure of, by recording and task number.
# rec_014 and rec_015 are not among them: the text gate holds those recordings, so their tasks are never extracted.
TASKS = (("rec_009", 3), ("rec_001", 3), ("rec_012", 2), ("rec_012", 3), ("rec_013", 1), ("rec_013", 2), ("rec_001", 4),
         ("rec_010", 1), ("rec_007", 3), ("rec_011", 1), ("rec_008", 1), ("rec_001", 1), ("rec_012", 1))
HEADER = ("// Generated by tools/app_fixtures.py from the committed exports (Dan's ruling 61). Do not edit by hand.\n"
          "// Fictional content only; every model number is Decider's answer as the named export recorded it.\n")


def _load(rel: str) -> Any:
    return json.loads((REPO / rel).read_text(encoding="utf-8"))


def build() -> dict[str, Any]:
    questions = load_route_questions(Settings())  # the floors: the gates' (sensitive) and a choice's (project)
    gate_floor, choice_floor = questions["sensitive"].min_confidence, questions["project"].min_confidence
    final = {r["file"]: r for r in _load(FINAL)["images"]}
    variants = _load(VARIANTS)["rows"]["cpu"]
    items: list[dict[str, Any]] = []
    for name in PHOTO_HOLDS:
        r = final[name]
        first = next(v for v in r["visits"] if v["status"] == "hold")
        verdict = {"image-sensitive": "sensitive", "image-unsure": "unsure"}[first["reason"]]
        items.append({
            "id": f"hold-{name.split('_')[0]}", "kind": "hold", "input": "photo", "ref": photo_id(Path(name)),
            "gate": "image gate", "verdict": verdict, "p": first["picture_p"][0], "floor": gate_floor,
            "viewer": {"type": "photo", "src": f"fixtures/{name}"},
            "source": {"export": FINAL, "item": name, "answer": "the image gate's read on the run's first visit"},
            "illustrative": False,
            "run_note": ("Held as sensitive in the run: a sensitive hold has no release." if verdict == "sensitive" else
                         "Held as unsure in the run and not released: its label is sensitive, so the run kept its "
                         "notice on the local record."),
        })
    gate = next(g for g in variants["gate"] if g["recording"] == TRANSCRIPT_HOLD)
    fixture = json.loads((REPO / "bench" / "fixtures" / "rec_014_hallway_at_the_symposium.json")
                         .read_text(encoding="utf-8"))["data"]
    p = max(w["p"] for w in gate["windows"])
    items.append({
        "id": f"hold-{TRANSCRIPT_HOLD}", "kind": "hold", "input": "recording", "ref": TRANSCRIPT_HOLD,
        "gate": "text gate", "verdict": "sensitive" if p >= gate_floor else "unsure", "p": p, "floor": gate_floor,
        "viewer": {"type": "transcript", "title": fixture["title"], "text": str(extract_text(fixture))},
        "source": {"export": VARIANTS, "item": f"rows.cpu.gate {TRANSCRIPT_HOLD}",
                   "answer": f"the text gate's read of its {len(gate['windows'])} window(s)"},
        "illustrative": False, "run_note": "Held as sensitive by the text gate: a sensitive hold has no release.",
    })
    for name in SCENES:
        r = final[name]
        img = r["image"]
        items.append({
            "id": f"scene-{name.split('_')[0]}", "kind": "scene", "input": "photo", "ref": photo_id(Path(name)),
            "scene": {"choice": img["scene_choice"], "confidence": img["scene_p"], "floor": choice_floor,
                      "options": img["scene_options"]},
            "viewer": {"type": "photo", "src": f"fixtures/{name}"},
            "source": {"export": FINAL, "item": name, "answer": "the scene read"},
            "illustrative": False, "run_note": "Asked the owner in the run; no answer was recorded.",
        })
    canonical = canonical_tasks(load_expected())
    for rid, n in TASKS:
        index = next(i for i, t in enumerate(variants["tasks"]) if t["recording"] == rid and t["n"] == n)
        answer, (_, expected, contact) = variants["tasks"][index], canonical[index]
        project = answer["judged"]["project"]
        sure = project["confidence"] >= project["floor"]
        items.append({
            "id": f"task-{rid}-{n}", "kind": "task", "input": "recording", "ref": f"{rid} #{n}",
            "text": expected.task.content, "due": expected.task.due_string, "from": contact.organisation or None,
            "project": {"choice": answer["answers"]["project"]["choice"], "confidence": project["confidence"],
                        "floor": project["floor"], "sure": sure,
                        "probabilities": {k: answer["answers"]["project"]["probabilities"][k] for k in PROJECTS}},
            "labels": ["pocket"] + ([f"proj:{project['answer']}"] if sure else []),
            "source": {"export": VARIANTS, "item": f"rows.cpu.tasks[{index}] ({rid} task {n})",
                       "answer": "the routing read's project question"},
            "illustrative": False,
        })
    return {"about": ("The companion app prototype's fixtures: fictional content, Decider's recorded answers. "
                      "Generated by tools/app_fixtures.py."),
            "projects": list(PROJECTS), "items": items}


def render(data: dict[str, Any]) -> str:
    return HEADER + "window.RATATOSKR_FIXTURES = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"


def pictures() -> list[str]:
    return [*PHOTO_HOLDS, *SCENES]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed fixtures, write nothing")
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        same = OUT.read_text(encoding="utf-8") == text and all(
            (PICTURES / name).read_bytes() == (REPO / "bench" / "images" / name).read_bytes() for name in pictures())
        print("app/fixtures.js and app/fixtures/: " + ("identical" if same else "DIFFER"))
        return 0 if same else 1
    OUT.write_bytes(text.encode("utf-8"))
    PICTURES.mkdir(parents=True, exist_ok=True)
    for name in pictures():
        shutil.copyfile(REPO / "bench" / "images" / name, PICTURES / name)
    print(f"wrote {OUT.relative_to(REPO)} ({len(build()['items'])} items) and {len(pictures())} pictures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
