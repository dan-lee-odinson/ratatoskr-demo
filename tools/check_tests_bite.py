def pytest(targets):
    done = subprocess.run([PY, "-m", "pytest", "-q", "-x", "-p", "no:cacheprovider", *targets],
                          capture_output=True, text=True)
    return done.returncode


def snapshot():
    """Hash every source file, so we can prove each mutation was undone."""
    roots = ("ratatoskr_demo", "tests", "bench", "patterns")
    return {str(f): hashlib.sha256(f.read_bytes()).hexdigest()
            for root in roots for f in Path(root).rglob("*")
            if f.is_file() and "__pycache__" not in f.parts and "raw" not in f.parts}


def check_anchors():
    for name, path, old, new, targets in MUTATIONS:
        if path is not None:
            count = Path(path).read_text(encoding="utf-8").count(old)
            assert count == 1, f"{name}: anchor found {count} times in {path}"


def main():
    check_anchors()
    assert pytest(["tests"]) == 0, "suite must be green before mutating"
    before = snapshot()
    results = []
    for name, path, old, new, targets in MUTATIONS:
        if path is None:  # C6: plant a file instead of editing one
            planted = Path("ratatoskr_demo/_planted_key.py")
            planted.write_text("KEY = " + PLANTED[old] + "\n", encoding="utf-8")
            code = pytest(targets)
            planted.unlink()
        else:
            p = Path(path)
            original = p.read_bytes()
            text = original.decode("utf-8")
            p.write_bytes(text.replace(old, new).encode("utf-8"))
            code = pytest(targets)
            p.write_bytes(original)
        results.append((name, "RED (caught)" if code != 0 else "GREEN - TEST DOES NOT BITE"))
        print(f"{results[-1][1]:28} {name}", flush=True)
    assert snapshot() == before, "a mutation was not restored"
    assert pytest(["tests"]) == 0, "suite must be green again after restoring"
    bad = [n for n, r in results if not r.startswith("RED")]
    print(f"\n{len(results) - len(bad)}/{len(results)} mutations caught; suite green again; tree clean.")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    if sys.argv[1:] == ["--anchors"]:
        check_anchors()
        print(f"{len(MUTATIONS)} mutations; every anchor found exactly once.")
    else:
        main()
