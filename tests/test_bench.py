def test_results_md_records_the_hash_of_the_current_run_bench():
    """RESULTS.md is generated, never hand-edited: it must name the run_bench.py it came from."""
    results = REPO / "bench" / "RESULTS.md"
    if not results.exists():
        pytest.skip("bench/RESULTS.md is written by the first bench run")
    text = results.read_text(encoding="utf-8")
    assert "Generated by bench/run_bench.py. Do not edit by hand" in text
    [recorded] = re.findall(r"git blob `([0-9a-f]{16})`", text)
    assert recorded == bench.git_blob_hash(REPO / "bench" / "run_bench.py"), \
        "run_bench.py changed since RESULTS.md was generated: run the bench again"


def test_the_hash_is_gits_blob_hash(tmp_path):
    f = tmp_path / "x.py"
    f.write_bytes(b"hello\n")
    assert bench.git_blob_hash(f) == "ce013625030ba8db"  # `git hash-object` of "hello\n"
    f.write_bytes(b"hello\r\n")
    assert bench.git_blob_hash(f) == "ce013625030ba8db"  # line endings as git stores them


class BenchMantle(FakeMantle):
    """Bedrock for the bench: extraction returns each recording's canonical tasks; routing answers as expected."""

    def __init__(self):
        super().__init__()
        self.by_transcript = {}
        for directory in FIXTURE_DIRS:
            for path in Path(directory).glob("rec_*.json"):
                body = json.loads(path.read_text(encoding="utf-8"))
                block = body.get("expected") or {}
                if body["data"].get("transcript") and block.get("contact"):
                    tasks = [{k: t[k] for k in ("content", "due_string", "notes")} for t in block["tasks"]]
                    self.by_transcript[body["data"]["transcript"]] = extraction_json(block["contact"], tasks)
        self.expected = {t.task.content: t for r in load_expected() for t in r.tasks}

    def chat(self, request):
        body = json.loads(request.content)
        system, user = body["messages"][0]["content"], body["messages"][1]["content"]
        if system.startswith("You answer six typed questions"):
            state = json.loads(user.split("State:\n", 1)[1])
            e = self.expected.get(state["task"]["content"])
            self.content = json.dumps({
                "project": {"choice": e.project if e else "other", "confidence": 0.9},
                "someone_waiting": {"probability_yes": 0.9 if (e and e.someone_waiting) else 0.1},
                "hard_deadline": {"probability_yes": 0.9 if (e and e.hard_deadline) else 0.1},
                "worth_researching_soon": {"probability_yes": 0.9 if (e and e.worth_researching_soon) else 0.1},
                "real_commitment": {"probability_yes": 0.9 if (e is None or e.real_commitment) else 0.1},
                "sensitive": {"probability_yes": 0.9 if (e and e.sensitive) else 0.1},
            })
        else:
            self.content = next((reply for transcript, reply in self.by_transcript.items() if transcript in user),
                                extraction_json(tasks=[]))
        return super().chat(request)


def mocked_run(tmp_path, *, jev=None, rotations=0, gate_reply=None, rotation_from=None, **kwargs):
    from ratatoskr_demo.decider import DeciderClient
    from ratatoskr_demo.source_gate import SourceGate

    write_baseline(tmp_path)
    settings = make_settings(tmp_path, {"paths": {"model_baseline": str(tmp_path / "model_baseline.json")}})
    mantle = BenchMantle()
    with respx.mock(assert_all_called=False) as router:
        router.get(f"{BASE}/models").mock(side_effect=mantle.models)
        router.post(f"{BASE}/chat/completions").mock(side_effect=mantle.chat)
        decider = attach(router)
        if gate_reply is not None:
            decider.gate_reply = gate_reply
        gate = SourceGate(DeciderClient("http://127.0.0.1:8000", http=httpx.Client()),
                          load_route_questions(Settings())["sensitive"])
        client = BedrockClient(settings, make_spend_ledger(settings), http=httpx.Client())
        run = bench.run_bench(settings, bedrock=client, decider=decider.router(), jev=jev, rotations=rotations,
                              gate=gate, rotation_from=rotation_from, out=lambda line: None, **kwargs)
        text = bench.render(run, settings=settings, spend=client.spend.summary(),
                            versions={"test": "mocked"}, when="2026-10-16 00:00 UTC")
    return run, text, mantle, decider


