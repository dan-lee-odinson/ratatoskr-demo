def test_the_rotation_can_be_carried_over_from_an_earlier_raw_file(tmp_path, monkeypatch):
    from ratatoskr_demo.errors import ConfigurationError

    monkeypatch.setattr(bench, "RAW_DIR", tmp_path / "raw")
    (tmp_path / "a").mkdir()
    first, _, _, _ = mocked_run(tmp_path / "a", rotations=7)
    bench.write_raw(first, "2026-10-17 12:00 UTC")
    [raw] = (tmp_path / "raw").glob("run-*.json")
    questions = load_route_questions(Settings())
    carried = bench.carried_rotation(raw, questions)
    assert (carried.flipped, carried.first_picks, carried.answers, carried.choices) == (
        first.rotation.flipped, first.rotation.first_picks, first.rotation.answers, first.rotation.choices)
    data = json.loads(raw.read_text(encoding="utf-8"))
    data["rotation"]["choices"][0]["task"] = "a task that is not in the fixtures"
    other = tmp_path / "other.json"
    other.write_text(json.dumps(data), encoding="utf-8")
    with pytest.raises(ConfigurationError, match="canonical tasks"):
        bench.carried_rotation(other, questions)
    raw_text = raw.read_text(encoding="utf-8")  # the raw file now carries due strings too: still no transcript
    for directory in FIXTURE_DIRS:
        for path in Path(directory).glob("rec_*.json"):
            transcript = json.loads(path.read_text(encoding="utf-8"))["data"].get("transcript") or ""
            assert not overlap(transcript, raw_text, 8), path.name


def test_the_bench_refuses_to_run_while_the_loop_holds_its_lock(tmp_path):
    from ratatoskr_demo.errors import ConfigurationError
    from ratatoskr_demo.runlock import hold_loop_lock, loop_is_running, refuse_while_loop_runs

    assert not loop_is_running(tmp_path)
    with hold_loop_lock(tmp_path):
        assert loop_is_running(tmp_path)
        with pytest.raises(ConfigurationError, match="--loop is running"):
            refuse_while_loop_runs(tmp_path, "the bench")
        with pytest.raises(ConfigurationError, match="already running"):
            with hold_loop_lock(tmp_path):
                pass
    assert not loop_is_running(tmp_path)


def test_results_can_be_re_rendered_from_the_saved_state_with_a_prior_rotation_beside_it(tmp_path, monkeypatch):
    """Dan's overnight plan: RESULTS.md gets the new rotation beside the 04:49 one without asking a model again."""
    import argparse

    monkeypatch.setattr(bench, "RAW_DIR", tmp_path / "raw")
    monkeypatch.setattr(bench, "RESULTS", tmp_path / "RESULTS.md")
    (tmp_path / "a").mkdir()
    run, _, _, _ = mocked_run(tmp_path / "a", rotations=7)
    bench.write_raw(run, "2026-10-18 03:00 UTC")
    state = bench.save_state(run, versions={"test": "mocked", "machine": "the laptop's CPU, 4 threads; an old wording"},
                             spend={"total_usd": 0}, when="2026-10-18 03:00 UTC")
    [raw] = (tmp_path / "raw").glob("run-*.json")
    prior = tmp_path / "prior.json"
    data = json.loads(raw.read_text(encoding="utf-8"))
    data["rotation"]["choices"][0]["choices"][0] = "other"  # one more flip in the prior measurement
    prior.write_text(json.dumps(data), encoding="utf-8")
    settings = make_settings(tmp_path)

    def args(prior_path):
        return argparse.Namespace(render_from=state, rotation_from=raw, rotation_note="", prior_rotation_from=prior_path,
                                  prior_rotation_note="measured with the pre-7b wording", rotation_conditions=None,
                                  conditions="another job paused; the laptop otherwise idle",
                                  as_measured="on 18 Oct; the re-measure replaces these numbers.",
                                  out=bench.RESULTS, note=["asked with the questions of 18 Oct"])

    assert bench.rerender(args(raw), settings) == 0
    text = (tmp_path / "RESULTS.md").read_text(encoding="utf-8")
    assert "\n\n**[as measured]** on 18 Oct; the re-measure replaces these numbers.\n\n" in text  # ruling 15
    assert "re-rendered" in text and "Beside it, the prior measurement" in text and "The flip rate did not move" in text
    assert "(measured with the pre-7b wording)" in text
    assert "## Sure and wrong (canonical tasks)" in text  # ruling 8: computed, question by question
    assert "| machine | the laptop's CPU, 4 threads; another job paused; the laptop otherwise idle |" in text
    assert "an old wording" not in text  # ruling 10: the conditions are restated, not appended
    assert "- asked with the questions of 18 Oct\n" in text  # --note (ruling 40)
    assert bench.rerender(args(prior), settings) == 0
    assert "The flip rate moved from" in (tmp_path / "RESULTS.md").read_text(encoding="utf-8")
    # and through the command line, as the overnight chain runs it (no --rotations: the default must not refuse)
    assert bench.main(["--render-from", str(state), "--rotation-from", str(raw), "--prior-rotation-from", str(prior)]) == 0



def test_sure_and_wrong_counts_each_direction_per_question():
    """Ruling 8: where a backend was sure and still disagreed with the label, the report says so, per question."""
    from ratatoskr_demo.judge import Judgement

    tasks = [bench.BenchTask(rid, e.task, c, e) for rid, e, c in bench.canonical_tasks(load_expected())][:4]
    asked = []
    for t in tasks:
        want = t.expected.hard_deadline
        asked.append(bench.Asked("decider", judged={"hard_deadline": Judgement(
            "hard_deadline", "p", 0.9, 0.7, not want, answer=not want)}))  # sure, and always the opposite
    lines = bench.sure_and_wrong({"decider": asked}, tasks)
    labelled_yes = sum(1 for t in tasks if t.expected.hard_deadline)
    row = next(line for line in lines if line.startswith("| decider | hard_deadline |"))
    assert row == f"| decider | hard_deadline | 4 | 4 | {labelled_yes} | {4 - labelled_yes} |"
    assert bench.sure_and_wrong({"decider": []}, [])[-1] == "| (none) | | | | | |"
