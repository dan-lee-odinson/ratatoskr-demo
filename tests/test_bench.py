    assert not any("surgery got moved up" in json.dumps(body) for body in mantle.bodies)  # the transcript: never
    assert "| rec_014 | 1 / 1 | 0.95 | HOLD (sensitive) | HOLD |" in text
    assert "matched the expected one for 12/12 (100%) recordings" in text


