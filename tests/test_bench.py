def test_a_mocked_bench_runs_every_column_and_scores_against_the_expected_answers(tmp_path):
    from tests.test_jev import FakeJev

    run, text, mantle, decider = mocked_run(tmp_path, jev=FakeJev().router(), rotations=7)
    assert set(run.asked) == {"decider", "bedrock", "jev"}
    canonical = sum(len(r.tasks) for r in load_expected())
    assert len(run.tasks) == canonical and all(t.expected is not None for t in run.tasks)
    assert all(len(asked) == len(run.tasks) for asked in run.asked.values())
    scores = bench.agreement(run.asked["bedrock"], run.tasks)  # the fake Bedrock answers as expected
    assert all(scores[q]["agree"] == scores[q]["matched"] for q in bench.QUESTIONS)  # priority included
    labelled = {q: sum(1 for r in load_expected() for e in r.tasks if getattr(e, q) is not None)
                for q in ("someone_waiting", "hard_deadline", "worth_researching_soon")}
    assert all(scores[q]["matched"] == canonical for q in bench.QUESTIONS if q not in labelled)
    assert all(scores[q]["matched"] == n for q, n in labelled.items())  # explicit labels; None is not scored
    assert labelled["worth_researching_soon"] < canonical and labelled["someone_waiting"] == canonical  # 7a
    assert run.rotation is not None and run.rotation.tasks == canonical and run.rotation.rotations == 7
    assert len(decider.bodies) == canonical + canonical + canonical * 7  # extracted, canonical, rotations
    assert all(len(asked) == canonical for asked in run.canonical.values())
    for heading in ("## Source-text gate", "## Per backend", "## Agreement with the expected answers",
                    "## Agreement on the canonical tasks", "## Option order", "## Per task"):
        assert heading in text
    assert len(run.gated) == 12 and all(g.status == "clear" for g in run.gated)  # the fake gate clears all


